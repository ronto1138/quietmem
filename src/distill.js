// Nightly distillation: for each project with conversation on a given day, ask a model to PROPOSE
// memories. Nothing is written to any memory until a human reviews the proposals.
//
// The model is whatever command you configure (distill.command), fed the prompt on stdin and expected
// to print JSON. By default that is Claude Code in non-interactive mode (`claude -p`), which runs on the
// user's own subscription; the variables in distill.scrubEnv are removed from its environment so it can
// never fall back to a pay-per-token API key by accident. Other choices: `codex exec`, `ollama run <model>`,
// `llm`, or any script. QUIETMEM_DISABLE=1 is set so the distiller's own session is not indexed or recalled.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { looksLikeSecret } from './redact.js';
import { expire, pendingFor } from './proposals.js';
import { expandHome } from './config.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const TYPES = new Set(['feedback', 'project', 'reference', 'user']);

export const dayKey = (d, tz) => new Intl.DateTimeFormat('en-CA', { timeZone: tz }).format(d);

export function parseProposals(raw) {
  const m = String(raw).match(/\{[\s\S]*\}/);
  const j = JSON.parse(m ? m[0] : raw);
  const out = [];
  for (const p of j.proposals || []) {
    if (!p || !TYPES.has(p.type) || !p.body || !p.name || !p.file) continue;
    if (looksLikeSecret(`${p.body} ${p.description || ''} ${p.evidence || ''}`)) continue;   // never propose secrets
    p.file = String(p.file).replace(/[^\w.-]/g, '_');
    if (!p.file.endsWith('.md')) p.file += '.md';
    p.action = p.action === 'update' ? 'update' : 'new';
    out.push(p);
  }
  return out.slice(0, 5);
}

export function renderProposals(project, day, proposals, meta) {
  const L = [`# Memory proposals · ${project} · ${day}`, ''];
  L.push(`> Generated by quietmem on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC from ${meta.chunks} chunks`);
  L.push(`> (${meta.chars.toLocaleString('en-US')} characters) of that day's conversation${meta.truncated ? ', truncated to the most recent part' : ''}.`);
  L.push('> **Nothing here has been written yet.** Change each "pending" to "accepted" or "rejected" and apply the accepted ones.', '');
  if (!proposals.length) L.push('_No proposals: nothing that day was worth remembering._', '');
  proposals.forEach((p, i) => {
    L.push(`## ${i + 1}. [${p.action}] ${p.type} · \`${p.file}\``, '');
    L.push(`**For the index:** ${p.description}`, '');
    if (p.evidence) L.push(`**Evidence:** ${p.evidence}`, '');
    L.push('```markdown', '---', `name: ${p.name}`, `description: ${JSON.stringify(p.description)}`, 'metadata:', `  type: ${p.type}`, '---', '', p.body.trim(), '```', '');
    L.push('**Decision:** pending', '');
  });
  return L.join('\n');
}

export async function distill(db, cfg, { day, project: only, force = false, log = () => {}, print = console.log }) {
  const d = cfg.distill;
  mkdirSync(d.outDir, { recursive: true });
  for (const v of expire(d.outDir, { days: d.expireDays })) log({ file: v.file, reason: 'expired', pending: v.pending });

  await db.query('SET statement_timeout = 0');
  const { rows: projects } = await db.query(`
    SELECT project, count(*)::int chunks, sum(length(content))::int chars FROM chunks
     WHERE (ts AT TIME ZONE $2)::date = $1::date GROUP BY 1 ORDER BY 3 DESC`, [day, d.timezone]);

  const promptPath = d.promptFile ? expandHome(d.promptFile) : join(HERE, '..', 'prompts', 'distill.md');
  const prompt = readFileSync(promptPath, 'utf8').replaceAll('{{LANGUAGE}}', d.language);
  const context = d.contextFiles.map(expandHome).filter(existsSync)
    .map(f => `## Context file: ${f}\n${readFileSync(f, 'utf8')}`).join('\n\n');
  const env = { ...process.env, QUIETMEM_DISABLE: '1' };
  for (const k of d.scrubEnv) delete env[k];
  const cwd = join(tmpdir(), 'quietmem-distill'); mkdirSync(cwd, { recursive: true });

  let done = 0;
  for (const p of projects) {
    if (only && p.project !== only) continue;
    const file = join(d.outDir, `${day}-${p.project}.md`);
    if (existsSync(file) && !force) { log({ project: p.project, reason: 'exists' }); continue; }
    if (p.chars < d.minChars) { log({ project: p.project, reason: 'too_little_text', chars: p.chars }); continue; }
    const pending = pendingFor(d.outDir, p.project);
    if (pending >= d.maxPending) { log({ project: p.project, reason: 'too_many_pending', pending }); continue; }
    if (done >= d.maxProjects) { log({ project: p.project, reason: 'max_projects' }); continue; }

    const { rows } = await db.query(`
      SELECT to_char(ts AT TIME ZONE $3, 'HH24:MI') h, content FROM chunks
       WHERE project = $1 AND (ts AT TIME ZONE $3)::date = $2::date ORDER BY id`, [p.project, day, d.timezone]);
    let convo = rows.map(r => `${r.h} ${r.content}`).join('\n\n');
    const truncated = convo.length > d.maxChars;
    if (truncated) convo = convo.slice(-d.maxChars);
    const idxPath = d.memoryIndex ? expandHome(d.memoryIndex.replaceAll('{project}', p.project)) : null;
    const index = idxPath && existsSync(idxPath) ? readFileSync(idxPath, 'utf8') : '(this project has no memories yet)';
    const input = `${prompt}\n\n${context ? context + '\n\n' : ''}## Index of existing memories for project ${p.project}\n${index}\n\n## Conversation on ${day} in ${p.project} (each block starts with the time)\n${convo}\n`;

    const [cmd, ...args] = d.command;
    const t0 = Date.now();
    const r = spawnSync(cmd, args, { input, env, cwd, encoding: 'utf8', timeout: d.timeoutMs, maxBuffer: 16 * 1024 * 1024, shell: !!d.shell });
    const ms = Date.now() - t0;
    if (r.status !== 0) { log({ project: p.project, reason: 'command_error', status: r.status, ms }); continue; }
    let proposals;
    try { proposals = parseProposals(r.stdout); }
    catch {
      writeFileSync(join(d.outDir, `${day}-${p.project}.raw.txt`), r.stdout);
      log({ project: p.project, reason: 'invalid_json', ms });
      continue;
    }
    writeFileSync(file, renderProposals(p.project, day, proposals, { chunks: p.chunks, chars: convo.length, truncated }));
    log({ project: p.project, proposals: proposals.length, chunks: p.chunks, chars: convo.length, truncated, ms });
    print(`${p.project}: ${proposals.length} proposals (${Math.round(ms / 1000)} s)`);
    done++;
  }
  if (!done) print(`nothing to distill for ${day}`);
  return done;
}
